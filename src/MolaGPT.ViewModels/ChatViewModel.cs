    public ChatViewModel(
        ProviderRegistry providers,
        MessageRepository? messageRepo,
        ConversationRepository? conversationRepo,
        PersonaListViewModel? personas,
        SettingsRepository? settingsRepo)
    {
        _providers = providers;
        _messageRepo = messageRepo;
        _conversationRepo = conversationRepo;
        _personas = personas;
        _settingsRepo = settingsRepo;

        Messages.CollectionChanged += (_, _) =>
        {
            OnPropertyChanged(nameof(IsEmpty));
            UpdateLatestAssistantFlags();
        };
        _providers.Changed += (_, _) => RefreshActiveModelAfterProviderChange();

        // When the user edits the active persona's prompt, the resolved
        // ActivePersonaSystemPrompt changes value-wise even if the id didn't.
        if (_personas is not null)
            _personas.PersonasChanged += (_, _) =>
            {
                OnPropertyChanged(nameof(ActivePersona));
                OnPropertyChanged(nameof(ActivePersonaAvatar));
                OnPropertyChanged(nameof(ActivePersonaName));
                OnPropertyChanged(nameof(ActivePersonaSystemPrompt));
            };

        ActivePersonaId = ResolveDefaultPersonaId();
        TryAutoPickActive();
    }

    /// <summary>If no provider is currently active, pick the first registered one.</summary>
    public void TryAutoPickActive()
    {
        if (ActiveProvider is not null && ActiveModel is not null) return;
        var first = _providers.Providers.FirstOrDefault();
        if (first is null || first.Models.Count == 0) return;
        ActiveProvider = first;
        ActiveModel = first.Models[0];
    }

    public void SetActive(IChatProvider provider, ProviderModel model)
    {
        ActiveProvider = provider;
        ActiveModel = model;
    }

    public bool SetActiveByIds(string? providerId, string? modelId, bool ignoreConversationBoundary = false)
    {
        if (string.IsNullOrWhiteSpace(providerId) || string.IsNullOrWhiteSpace(modelId))
            return false;

        var resolved = _providers.FindModel(providerId, modelId);
        if (resolved is null) return false;
        if (!ignoreConversationBoundary && !CanSwitchToProvider(resolved.Value.Provider))
            return false;

        SetActive(resolved.Value.Provider, resolved.Value.Model);
        RememberModeSelection(resolved.Value.Provider.ToAppMode(), providerId, modelId);
        return true;
    }

    public bool CanSwitchToProvider(IChatProvider provider)
    {
        // Boundary is by capability, not wallet: a Chat (cloud) conversation can
        // only continue with the proxy; a local-agent conversation (Work or BYOK)
        // can continue with either local-tools or any BYOK provider.
        var family = GetCurrentConversationProviderFamily();
        return family switch
        {
            ConversationProviderFamily.Chat => provider.Kind == ProviderKind.MolaGptProxy,
            ConversationProviderFamily.Agent => provider.Kind != ProviderKind.MolaGptProxy,
            _ => true
        };
    }

    // ===== Three-way mode slider (BYOK / Chat / Work) =====
    // The slider is the UI truth source for AppMode. Switching modes routes to
    // each mode's representative provider: Chat → molagpt-proxy, Work →
    // molagpt-local-tools, BYOK → the user's last-chosen BYOK provider (or the
    // first registered one). The active provider drives CurrentMode back, so the
    // slider thumb always reflects reality. Per-mode (provider,model) memory
    // persists via SettingsRepository.

    private const string ModeLastProviderKeyPrefix = "mode_last_provider_";
    private const string ModeLastModelKeyPrefix = "mode_last_model_";

    /// <summary>Switch to the representative provider of the given mode. Returns
    /// false (and surfaces a login request via <paramref name="needsLogin"/>) when
    /// the target MolaGPT-account provider isn't registered (user not signed in).</summary>
    public bool SwitchToMode(AppMode mode, out bool needsLogin)
    {
        needsLogin = false;
        var (providerId, modelId) = ResolveModeTarget(mode, out needsLogin);
        if (providerId is null || modelId is null) return false;

        if (SetActiveByIds(providerId, modelId, ignoreConversationBoundary: true))
        {
            RememberModeSelection(mode, providerId, modelId);
            return true;
        }
        return false;
    }

    private (string? ProviderId, string? ModelId) ResolveModeTarget(AppMode mode, out bool needsLogin)
    {
        needsLogin = false;
        switch (mode)
        {
            case AppMode.Chat:
            {
                var p = _providers.GetById(MolaGptProviderIds.Proxy);
                if (p is null) { needsLogin = true; return (null, null); }
                return (p.Id, RecallModel(p) ?? p.Models.FirstOrDefault()?.Id);
            }
            case AppMode.Work:
            {
                // "MolaGPT Work" is the unified local-agent capability. Land on the
                // agent provider the user last used (shared-quota Work or a BYOK
                // provider); fall back to shared-quota Work, then the first BYOK.
                var lastAgentId = _settingsRepo?.Get(ModeLastProviderKeyPrefix + "agent");
                var provider = string.IsNullOrWhiteSpace(lastAgentId) ? null : _providers.GetById(lastAgentId!);
                if (provider is null || provider.Kind == ProviderKind.MolaGptProxy)
                    provider = _providers.GetById(MolaGptProviderIds.LocalTools)
                               ?? _providers.Providers.FirstOrDefault(p => !p.Kind.IsMolaGptAccount());
                if (provider is null) { needsLogin = true; return (null, null); }
                return (provider.Id, RecallModel(provider) ?? provider.Models.FirstOrDefault()?.Id);
            }
            default:
            {
                // BYOK: last-chosen BYOK provider if still registered, else first BYOK.
                var byok = _providers.Providers.Where(p => !p.Kind.IsMolaGptAccount()).ToList();
                if (byok.Count == 0) return (null, null);
                var lastId = _settingsRepo?.Get(ModeLastProviderKeyPrefix + "byok");
                var chosen = byok.FirstOrDefault(p => p.Id == lastId) ?? byok[0];
                return (chosen.Id, RecallModel(chosen) ?? chosen.Models.FirstOrDefault()?.Id);
            }
        }
    }

    private string? RecallModel(IChatProvider provider)
    {
        var key = ModeLastModelKeyPrefix + provider.Id;
        var recalled = _settingsRepo?.Get(key);
        return string.IsNullOrWhiteSpace(recalled) ? null : recalled;
    }

    private void RememberModeSelection(AppMode mode, string providerId, string modelId)
    {
        if (_settingsRepo is null) return;
        _settingsRepo.Set(ModeLastProviderKeyPrefix + mode.ToString().ToLowerInvariant(), providerId);
        _settingsRepo.Set(ModeLastModelKeyPrefix + providerId, modelId);
        // The unified "MolaGPT Work" switcher button lands on whichever agent
        // provider was last active — shared-quota Work or a BYOK provider.
        if (mode.IsLocalAgent())
            _settingsRepo.Set(ModeLastProviderKeyPrefix + "agent", providerId);
    }

    public void SaveConversationSystemPrompt(string? prompt)
    {
        ConversationSystemPrompt = string.IsNullOrWhiteSpace(prompt) ? null : prompt.Trim();
        if (_conversationRepo is null || string.IsNullOrEmpty(ConversationId)) return;
        var existing = _conversationRepo.Get(ConversationId!);
        if (existing is null) return;
        _conversationRepo.Upsert(existing with { SystemPrompt = ConversationSystemPrompt });
    }

    /// <summary>
    /// Bind the current conversation to a persona (or unbind by passing null).
    /// Persists immediately when a conversation row exists; otherwise the
    /// selection is captured on the first send via <see cref="InitializeConversationIfNeeded"/>.
    /// </summary>
    public void SaveActivePersona(string? personaId)
    {
        ActivePersonaId = string.IsNullOrEmpty(personaId) ? null : personaId;
        if (_conversationRepo is null || string.IsNullOrEmpty(ConversationId)) return;
        var existing = _conversationRepo.Get(ConversationId!);
        if (existing is null) return;
        _conversationRepo.Upsert(existing with { PersonaId = ActivePersonaId });

        // Push the new persona label into the sidebar so the BYOK badge
        // refreshes without requiring a user message to be sent first.
        // Pass "" (not null) when un-binding so the sidebar treats it as
        // an explicit clear rather than "no info, keep existing".
        ConversationTouched?.Invoke(this, new ConversationTouchedEventArgs(
            ConversationId!,
            ConversationTitle,
            DateTimeOffset.FromUnixTimeMilliseconds(existing.UpdatedAt),
            existing.ProviderId,
            ActivePersonaId is null ? "" : ActivePersona?.Name));
    }

    /// <summary>
    /// Set whether the conversation-level prompt overrides or appends to the
    /// persona prompt. Accepts "override" / "append" — anything else falls
    /// back to "override".
    /// </summary>
    public void SaveSystemPromptMode(string? mode)
    {
        SystemPromptMode = string.Equals(mode, "append", StringComparison.OrdinalIgnoreCase) ? "append" : "override";
        if (_conversationRepo is null || string.IsNullOrEmpty(ConversationId)) return;
        var existing = _conversationRepo.Get(ConversationId!);
        if (existing is null) return;
        _conversationRepo.Upsert(existing with { SystemPromptMode = SystemPromptMode });
    }

    public void StartDraftConversation()
    {
        _messageLoadVersion++;
        foreach (var existing in Messages) existing.Dispose();
        Messages.Clear();
        _pendingOlderMessages.Clear();
        ConversationId = null;
        ConversationTitle = "新对话";
        ConversationSystemPrompt = null;
        ActivePersonaId = ResolveDefaultPersonaId();
        SystemPromptMode = "override";
        ContextGauge.Reset();
        // New conversation has no working directory yet — clear artifacts
        // and dismiss the panel so the previous conversation's files don't stick.
        RefreshArtifacts();
    }

    private string? ResolveDefaultPersonaId() =>
        _personas?.Find(PersonaListViewModel.BuiltinDefaultId) is not null
            ? PersonaListViewModel.BuiltinDefaultId
            : null;

    public async Task LoadConversationAsync(string conversationId, bool loadAllMessagesImmediately = false)
    {
        ConversationId = conversationId;
        // Cleared here and restored from the loaded messages below. Leaving it
        // cleared was the first attempt and it was wrong: reopening a conversation
        // made the gauge vanish until the user sent another turn, which reads as the
        // feature being broken rather than as "not measured yet".
        ContextGauge.Reset();
        var loadVersion = ++_messageLoadVersion;
        var loadUiContext = SynchronizationContext.Current;

        // Show the loading overlay for the whole load. The overlay's first
        // paint is forced synchronously by the Desktop layer BEFORE this method
        // runs its heavy work (see MainWindow.ConversationListBox_SelectionChanged),
        // because a flag flipped here can't paint while the UI thread is busy
        // building the FlowDocument. A fast (small) load finishes within a frame
        // so the overlay barely registers; its fade-in smooths the rare flash.
        IsConversationLoading = true;

        void FinishLoadingIndicator()
        {
            // Defer the hide to the back of the dispatcher queue so the first
            // batch of messages gets a layout/paint pass before the overlay
            // clears — otherwise it could vanish a frame before content shows.
            if (loadUiContext is not null)
                loadUiContext.Post(_ => { if (loadVersion == _messageLoadVersion) IsConversationLoading = false; }, null);
            else
                IsConversationLoading = false;
        }

        try
        {
            // Dispose any existing message VMs (their elapsed timers etc.)
            // before clearing the collection.
            foreach (var existing in Messages) existing.Dispose();
            Messages.Clear();
            _pendingOlderMessages.Clear();

            ConversationRow? conversationRow = null;
            if (_messageRepo is not null)
            {
                var readSw = System.Diagnostics.Stopwatch.StartNew();
                var snapshot = await Task.Run(() =>
                {
                    var messages = PrepareMessageSnapshot(_messageRepo.List(conversationId));
                    var conversation = _conversationRepo?.Get(conversationId);
                    return (messages, conversation);
                }).ConfigureAwait(true);
                PerfTrace?.Invoke("load.read+meta",
                    $"{readSw.Elapsed.TotalMilliseconds:N0} ms  msgs={snapshot.messages.Count}");

                if (loadVersion != _messageLoadVersion || ConversationId != conversationId)
                    return;

                conversationRow = snapshot.conversation;
                var prepared = snapshot.messages;

                // From the whole snapshot, not just the materialized tail: the
                // reading belongs to the conversation, and only the newest turns are
                // built up front.
                RestoreContextGauge(prepared);

                // Open at the END of the conversation. The newest messages are
                // what the user clicked to see, and materializing only those
                // keeps the cost of opening a 500-message conversation
                // proportional to the viewport instead of to the history —
                // every message we build here is a full markdown parse and
                // FlowDocument, on the UI thread. The rest waits in
                // _pendingOlderMessages until the user scrolls up.
                var materialized = new List<MessageViewModel>();
                if (loadAllMessagesImmediately)
                {
                    foreach (var message in prepared)
                        materialized.Add(CreateMessageViewModel(message));
                }
                else
                {
                    var tailStart = Math.Max(0, prepared.Count - TailBatch);
                    for (int i = tailStart; i < prepared.Count; i++)
                        materialized.Add(CreateMessageViewModel(prepared[i]));
                    if (tailStart > 0)
                        _pendingOlderMessages.AddRange(prepared.GetRange(0, tailStart));
                }
                _messages.ReplaceAll(materialized);
                OnPropertyChanged(nameof(HasOlderMessages));
                UpdateLatestAssistantFlags();
                PerfTrace?.Invoke("load.materialize",
                    $"{Messages.Count} shown, {_pendingOlderMessages.Count} parked");
            }

            conversationRow ??= _conversationRepo?.Get(conversationId);
            if (conversationRow is { } row2)
            {
                ConversationTitle = string.IsNullOrWhiteSpace(row2.Title) ? "新对话" : row2.Title;
                ConversationSystemPrompt = row2.SystemPrompt;
                ActivePersonaId = row2.PersonaId;
                SystemPromptMode = string.Equals(row2.SystemPromptMode, "append", StringComparison.OrdinalIgnoreCase)
                    ? "append" : "override";
                RestoreActiveModel(row2);
            }
            else
            {
                ConversationTitle = "新对话";
                ConversationSystemPrompt = null;
                ActivePersonaId = null;
                SystemPromptMode = "override";
            }

            // Surface any artifacts already sitting in this conversation's
            // working directory (from earlier python runs / uploads).
            RefreshArtifacts();
        }
        finally
        {
            // Covers success, the stale-version early return, and exceptions.
            // The deferred Post re-checks the load version, so a superseded
            // load never hides a newer load's indicator.
            FinishLoadingIndicator();
        }
    }

    private static List<PreparedMessage> PrepareMessageSnapshot(IReadOnlyList<MessageRow> rows)
    {
        var prepared = new List<PreparedMessage>(rows.Count);
        IReadOnlyList<SourceReference>? lastKnownSources = null;

        // Every retry attempt carries a full copy of that answer's body, so a
        // message the user regenerated a few times can hold megabytes of meta —
        // measured at 7.6 MB of attempts against 3.1 MB of actual content on one
        // deepresearch answer. Materializing all of it on load is pure waste:
        // MessageViewModel.HasRetryBar gates the attempt switcher on
        // IsLatestAssistant, so no older message can ever display them.
        //
        // Parse them for the newest assistant row only. Nothing writes meta back
        // for older rows either — UpdatePersistedMessage runs on the user's own
        // message or on the assistant turn currently being generated — so the
        // rows we skip keep their stored history untouched.
        var latestAssistantIndex = -1;
        for (var i = rows.Count - 1; i >= 0; i--)
        {
            if (rows[i].Role == ChatMessage.RoleAssistant)
            {
                latestAssistantIndex = i;
                break;
            }
        }

        for (var index = 0; index < rows.Count; index++)
        {
            var row = rows[index];
            var split = SplitInlineThinking(row.Content);
            string? modelLabel = null;
            string? providerLabel = null;
            string? thinkingText = split.Thinking;
            Usage? usage = null;
            IReadOnlyList<SourceReference>? sources = null;
            IReadOnlyList<AttachmentChip>? attachments = null;
            string? contentPartsJson = null;
            IReadOnlyList<MessageAttempt>? retryAttempts = null;
            IReadOnlyList<ToolCallDelta>? toolCalls = null;
            IReadOnlyList<ThinkingSegmentDelta>? thinkingSegments = null;
            var retryCurrent = 0;
            var wasStopped = false;
            var contextTokens = 0;
            var contextWindow = 0;
            var compactionTokensBefore = 0;
            var compactionTokensAfter = 0;
            string? compactionReason = null;
            if (!string.IsNullOrEmpty(row.Meta))
            {
                try
                {
                    using var doc = JsonDocument.Parse(row.Meta);
                    if (doc.RootElement.TryGetProperty("model", out var m) && m.ValueKind == JsonValueKind.String)
                        modelLabel = m.GetString();
                    if (doc.RootElement.TryGetProperty("provider", out var p) && p.ValueKind == JsonValueKind.String)
                        providerLabel = p.GetString();
                    if (doc.RootElement.TryGetProperty("thinking", out var th) && th.ValueKind == JsonValueKind.String)
                    {
                        var thinking = th.GetString();
                        if (!string.IsNullOrWhiteSpace(thinking))
                            thinkingText = MergeThinking(thinking, thinkingText);
                    }
                    usage = ParseUsage(doc.RootElement, "response_stats");
                    sources = ParseSources(doc.RootElement);
                    attachments = ParseAttachments(doc.RootElement);
                    contentPartsJson = ParseContentPartsJson(doc.RootElement);
                    if (index == latestAssistantIndex)
                        (retryAttempts, retryCurrent) = ParseRetry(doc.RootElement);
                    toolCalls = ParseToolCalls(doc.RootElement);
                    thinkingSegments = ParseThinkingSegments(doc.RootElement);
                    (toolCalls, thinkingSegments) = InferMissingTimelineIndexes(toolCalls, thinkingSegments);
                    retryAttempts = RestoreCurrentRetryAttemptState(
                        retryAttempts,
                        retryCurrent,
                        thinkingText,
                        thinkingSegments,
                        toolCalls);
                    wasStopped = doc.RootElement.TryGetProperty("stopped", out var st)
                                 && st.ValueKind == JsonValueKind.True;
                    contextTokens = ReadMetaInt(doc.RootElement, "context_tokens");
                    contextWindow = ReadMetaInt(doc.RootElement, "context_window");
                    compactionTokensBefore = ReadMetaInt(doc.RootElement, "compaction_tokens_before");
                    compactionTokensAfter = ReadMetaInt(doc.RootElement, "compaction_tokens_after");
                    compactionReason = ReadString(doc.RootElement, "compaction_reason");
                }
                catch (JsonException) { }
            }

            if (row.Role == ChatMessage.RoleAssistant && sources is { Count: > 0 })
                lastKnownSources = sources;
            else if (row.Role == ChatMessage.RoleAssistant
                     && sources is null
                     && lastKnownSources is { Count: > 0 }
                     && row.Content.Contains("<ref", StringComparison.OrdinalIgnoreCase))
                sources = lastKnownSources;

            var visibleContent = split.Visible;
            if (row.Role == ChatMessage.RoleAssistant)
            {
                var rewriteContexts = new List<PythonArtifactMarkdownRewriter.ArtifactContext>(
                    PythonArtifactMarkdownRewriter.CreateContexts(toolCalls));
                // Resolve inline BYOK generate_image links (![](generated-image-1.png))
                // to the real local attachment file so they render and can be zoomed.
                var imageContext = PythonArtifactMarkdownRewriter.CreateAttachmentContext(attachments);
                if (imageContext is not null)
                    rewriteContexts.Add(imageContext);
                visibleContent = PythonArtifactMarkdownRewriter.Rewrite(visibleContent, rewriteContexts);
            }

            prepared.Add(new PreparedMessage(
                row.Id,
                row.Role,
                visibleContent,
                thinkingText,
                row.CreatedAt,
                modelLabel,
                providerLabel,
                usage,
                sources,
                attachments,
                contentPartsJson,
                retryAttempts,
                retryCurrent,
                toolCalls,
                thinkingSegments,
                wasStopped,
                contextTokens,
                contextWindow,
                compactionTokensBefore,
                compactionReason,
                compactionTokensAfter));
        }

        return prepared;
    }

    private MessageViewModel CreateMessageViewModel(PreparedMessage prepared)
    {
        var vm = new MessageViewModel(prepared.Role, prepared.Content, DateTimeOffset.FromUnixTimeMilliseconds(prepared.CreatedAt))
        {
            MessageId = prepared.Id,
            ModelLabel = prepared.ModelLabel,
            ProviderLabel = prepared.ProviderLabel,
            Usage = prepared.Usage,
            Sources = prepared.Sources,
            Attachments = prepared.Attachments,
            ContentPartsJson = prepared.ContentPartsJson,
            RetryAttempts = prepared.RetryAttempts,
            RetryCurrentIndex = prepared.RetryCurrentIndex,
            WasStopped = prepared.WasStopped,
            ContextTokens = prepared.ContextTokens,
            ContextWindow = prepared.ContextWindow,
            CompactionTokensBefore = prepared.CompactionTokensBefore,
            CompactionReason = prepared.CompactionReason,
            CompactionTokensAfter = prepared.CompactionTokensAfter,
            AutoCollapseThinkingOnComplete = AutoCollapseThinking
        };
        if (prepared.ToolCalls is { Count: > 0 })
        {
            foreach (var toolCall in prepared.ToolCalls)
                vm.ApplyToolDelta(toolCall);
        }
        if (!string.IsNullOrWhiteSpace(prepared.Thinking))
        {
            vm.Thinking = prepared.Thinking;
            vm.ThinkingElapsedSeconds = 0;
            vm.IsThinkingActive = false;
            vm.RestoreThinkingSegments(prepared.ThinkingSegments is { Count: > 0 }
                ? prepared.ThinkingSegments
                : [new ThinkingSegmentDelta(prepared.Thinking, 0)]);
        }
        return vm;
    }

