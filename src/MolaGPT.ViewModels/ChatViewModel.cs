    public void RefreshArtifacts()
    {
        var scanned = string.IsNullOrEmpty(ConversationId)
            ? Array.Empty<MolaGPT.Core.Chat.Tools.PythonExecution.WorkspaceArtifact>()
            : MolaGPT.Core.Chat.Tools.PythonExecution.WorkspaceArtifactScanner.Scan(ConversationId);

        Artifacts.Clear();
        foreach (var artifact in scanned)
            Artifacts.Add(new ArtifactItemViewModel(artifact));

        OnPropertyChanged(nameof(HasArtifacts));
        OnPropertyChanged(nameof(ArtifactCount));
        ArtifactsRefreshed?.Invoke(this, HasArtifacts);
    }


