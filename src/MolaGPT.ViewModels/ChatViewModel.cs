    /// <summary>
    /// Put the gauge back to where the last turn left it.
    ///
    /// Walks backwards to the newest turn that recorded a reading. A turn that also
    /// compacted is deliberately skipped rather than used: its reading describes the
    /// context <em>before</em> the cut, and restoring that would show a nearly full
    /// ring over a history that was just summarized down. The agent applies the same
    /// rule to its own reporting — there is no honest number again until the model
    /// replies once more.
    /// </summary>
    private void RestoreContextGauge(IReadOnlyList<PreparedMessage> messages)
    {
        var restore = SelectContextRestore(messages
            .Select(m => new ContextRestoreCandidate(
                m.Role == ChatMessage.RoleAssistant,
                m.ContextTokens,
                m.ContextWindow,
                m.CompactionTokensBefore))
            .ToList());

        if (restore.CompactedBefore > 0)
        {
            // Known to have compacted, size unknown. Surfacing that is the point:
            // it is why the ring is blank.
            ContextGauge.ContextWindow = restore.Window;
            ContextGauge.LastCompactionTokensBefore = restore.CompactedBefore;
        }
        else if (restore.Tokens > 0)
        {
            ContextGauge.Apply(new ContextUsageDelta(restore.Tokens, restore.Window));
        }
    }

    internal readonly record struct ContextRestoreCandidate(
        bool IsAssistant,
        int Tokens,
        int Window,
        int CompactedBefore);

    internal readonly record struct ContextRestore(int Tokens, int Window, int CompactedBefore);

    /// <summary>The decision half of <see cref="RestoreContextGauge"/>, separated so
    /// the compaction rule can be pinned without standing up a repository.</summary>
    internal static ContextRestore SelectContextRestore(IReadOnlyList<ContextRestoreCandidate> turns)
    {
        for (var i = turns.Count - 1; i >= 0; i--)
        {
            var turn = turns[i];
            if (!turn.IsAssistant) continue;
            if (turn.CompactedBefore > 0) return new ContextRestore(0, turn.Window, turn.CompactedBefore);
            if (turn.Tokens > 0 && turn.Window > 0) return new ContextRestore(turn.Tokens, turn.Window, 0);
        }
        return default;
    }

    private static Usage? ParseUsage(JsonElement root, string propertyName)
    {
        if (!root.TryGetProperty(propertyName, out var node) || node.ValueKind != JsonValueKind.Object)
            return null;

        var prompt = ReadInt(node, "promptTokens") ?? ReadInt(node, "prompt_tokens");
        var completion = ReadInt(node, "completionTokens") ?? ReadInt(node, "completion_tokens") ?? ReadInt(node, "answerTokens");
        var total = ReadInt(node, "totalTokens") ?? ReadInt(node, "total_tokens");
        return prompt is null && completion is null && total is null
            ? null
            : new Usage(prompt, completion, total);
    }

    private static (IReadOnlyList<MessageAttempt>? Attempts, int Current) ParseRetry(JsonElement root)
    {
        if (!root.TryGetProperty("retry", out var retry) || retry.ValueKind != JsonValueKind.Object)
            return (null, 0);
        if (!retry.TryGetProperty("attempts", out var attemptsNode) || attemptsNode.ValueKind != JsonValueKind.Array)
            return (null, 0);

        var attempts = new List<MessageAttempt>();
        foreach (var item in attemptsNode.EnumerateArray())
        {
            if (item.ValueKind == JsonValueKind.String)
            {
                var legacySplit = SplitInlineThinking(item.GetString());
                attempts.Add(new MessageAttempt(
                    legacySplit.Visible,
                    null,
                    null,
                    null,
                    Thinking: legacySplit.Thinking));
                continue;
            }
            if (item.ValueKind != JsonValueKind.Object) continue;
            var content = item.TryGetProperty("content", out var contentNode) && contentNode.ValueKind == JsonValueKind.String
                ? contentNode.GetString() ?? string.Empty
                : string.Empty;
            var modelLabel = item.TryGetProperty("model_label", out var modelNode) && modelNode.ValueKind == JsonValueKind.String
                ? modelNode.GetString()
                : null;
            var split = SplitInlineThinking(content);
            var thinking = ReadString(item, "thinking");
            if (!string.IsNullOrWhiteSpace(split.Thinking))
                thinking = string.IsNullOrWhiteSpace(thinking) ? split.Thinking : MergeThinking(thinking, split.Thinking);
            var toolCalls = ParseToolCalls(item);
            var thinkingSegments = ParseThinkingSegments(item);
            (toolCalls, thinkingSegments) = InferMissingTimelineIndexes(toolCalls, thinkingSegments);
            attempts.Add(new MessageAttempt(
                split.Visible,
                modelLabel,
                ParseUsage(item, "response_stats"),
                ParseSources(item),
                item.TryGetProperty("stopped", out var stoppedNode) && stoppedNode.ValueKind == JsonValueKind.True,
                thinking,
                thinkingSegments,
                toolCalls));
        }

        var current = ReadInt(retry, "current") ?? Math.Max(0, attempts.Count - 1);
        current = Math.Max(0, Math.Min(current, Math.Max(0, attempts.Count - 1)));
        return attempts.Count == 0 ? (null, 0) : (attempts, current);
    }

    private static IReadOnlyList<MessageAttempt>? RestoreCurrentRetryAttemptState(
        IReadOnlyList<MessageAttempt>? attempts,
        int current,
        string? thinking,
        IReadOnlyList<ThinkingSegmentDelta>? thinkingSegments,
        IReadOnlyList<ToolCallDelta>? toolCalls)
    {
        if (attempts is not { Count: > 0 } || current < 0 || current >= attempts.Count)
            return attempts;

        var restored = attempts.ToList();
        var attempt = restored[current];
        restored[current] = attempt with
        {
            Thinking = !string.IsNullOrWhiteSpace(thinking) ? thinking : attempt.Thinking,
            ThinkingSegments = thinkingSegments is { Count: > 0 } ? thinkingSegments : attempt.ThinkingSegments,
            ToolCalls = toolCalls is { Count: > 0 } ? toolCalls : attempt.ToolCalls
        };
        return restored;
    }

    private static IReadOnlyList<ToolCallDelta>? ParseToolCalls(JsonElement root)
    {
        if (!root.TryGetProperty("tool_calls", out var node) || node.ValueKind != JsonValueKind.Array)
            return null;

        var list = new List<ToolCallDelta>();
        var fallbackIndex = 1;
        foreach (var item in node.EnumerateArray())
        {
            if (item.ValueKind != JsonValueKind.Object) continue;
            var name = ReadString(item, "name");
            var label = ReadString(item, "label");
            if (string.IsNullOrWhiteSpace(name) && string.IsNullOrWhiteSpace(label)) continue;
            name = RestoreToolName(name, label);
            var id = ReadString(item, "id");
            if (string.IsNullOrWhiteSpace(id))
                id = $"restored-tool-{fallbackIndex}";

            list.Add(new ToolCallDelta(
                id!,
                name,
                ReadString(item, "status") ?? "completed",
                label,
                ReadString(item, "summary"),
                ReadString(item, "detail"),
                ReadString(item, "arguments_json") ?? ReadString(item, "argumentsJson"),
                ReadString(item, "result_preview_json") ?? ReadString(item, "resultPreviewJson"),
                ReadString(item, "provider"),
                ReadInt(item, "content_offset") ?? ReadInt(item, "contentOffset"),
                ReadInt(item, "timeline_index") ?? ReadInt(item, "timelineIndex")));
            fallbackIndex++;
        }

        return list.Count == 0 ? null : list;
    }

