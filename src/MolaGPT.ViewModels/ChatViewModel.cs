            "查看图片" => "view_image",
            "图片分析" => "analyze_image",
            "生成图片" => "generate_image",
            _ => string.Empty
        };
    }

    private static IReadOnlyList<ThinkingSegmentDelta>? ParseThinkingSegments(JsonElement root)
